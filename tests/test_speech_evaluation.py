from __future__ import annotations

import json
import wave
from pathlib import Path

import pytest

from assistant.evaluation.speech import (
    SpeechCorpusUnavailable,
    load_speech_corpus,
    normalized_words,
    percentile,
    speech_condition_summary,
    word_error_rate,
)


def _write_silence(path: Path, *, seconds: float = 0.1) -> None:
    with wave.open(str(path), "wb") as audio:
        audio.setnchannels(1)
        audio.setsampwidth(2)
        audio.setframerate(16_000)
        audio.writeframes(b"\0\0" * int(16_000 * seconds))


def _manifest(status: str = "ready") -> dict:
    return {
        "corpus_id": "test-speech",
        "version": "1.0.0",
        "status": status,
        "language": "en",
        "license": "Test fixture",
        "consent_record": "Synthetic silence generated by the test suite.",
        "sample_format": "pcm_s16le",
        "sample_rate_hz": 16_000,
        "channels": 1,
        "thresholds": {"quiet-speech": 0.08, "controlled-noise": 0.15},
        "cases": [
            {
                "case_id": "silence.1",
                "audio": "silence.wav",
                "reference": "",
                "condition": "silence",
                "expected_behavior": "silence",
                "speaker_id": "synthetic",
            }
        ],
    }


def test_load_speech_corpus_validates_audio_and_produces_content_digest(tmp_path: Path):
    manifest_path = tmp_path / "corpus.json"
    audio_path = tmp_path / "silence.wav"
    _write_silence(audio_path)
    manifest_path.write_text(json.dumps(_manifest()), encoding="utf-8")

    first = load_speech_corpus(manifest_path)
    _write_silence(audio_path, seconds=0.2)
    second = load_speech_corpus(manifest_path)

    assert first.corpus.version == "1.0.0"
    assert first.cases[0].duration_seconds == pytest.approx(0.1)
    assert first.digest != second.digest


def test_template_or_missing_audio_is_reported_as_an_actionable_blocker(tmp_path: Path):
    manifest_path = tmp_path / "corpus.json"
    manifest_path.write_text(json.dumps(_manifest("template")), encoding="utf-8")

    with pytest.raises(SpeechCorpusUnavailable) as error:
        load_speech_corpus(manifest_path)

    assert any("status is template" in problem for problem in error.value.problems)
    assert any("missing audio asset" in problem for problem in error.value.problems)


def test_word_error_rate_normalizes_case_and_punctuation():
    assert normalized_words("Hello, ROWAN's assistant!") == ["hello", "rowan's", "assistant"]
    assert word_error_rate("Set a timer, please.", "set a timer please") == 0
    assert word_error_rate("one two three", "one four three") == pytest.approx(1 / 3)
    assert word_error_rate("", "unexpected speech") == 2


def test_speech_summaries_report_percentiles_and_condition_thresholds():
    samples = [
        {
            "condition": "quiet-speech",
            "word_error_rate": 0.05,
            "first_partial_seconds": 1.0,
            "final_seconds": 0.4,
        },
        {
            "condition": "quiet-speech",
            "word_error_rate": 0.09,
            "first_partial_seconds": 1.4,
            "final_seconds": 0.8,
        },
    ]

    summary = speech_condition_summary(samples, {"quiet-speech": 0.08})["quiet-speech"]

    assert summary["mean_word_error_rate"] == pytest.approx(0.07)
    assert summary["word_error_rate_passed"] is True
    assert summary["first_partial_p95_seconds"] == pytest.approx(1.38)
    assert percentile([], 0.95) is None
